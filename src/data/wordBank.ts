export const wordBank: WordCard[] = rawWordBank.map(
  ([char, word, sentence, emoji, category]) => ({
    char,
    word,
    sentence,
    emoji,
    category,
    hint: word,
  }),
);

const duplicateCharacters = wordBank.filter(
  (entry, index) => wordBank.findIndex((candidate) => candidate.char === entry.char) !== index,
);
const mismatchedExamples = wordBank.filter(
  (entry) => !entry.word.includes(entry.char) || !entry.sentence.includes(entry.char),
);

if (duplicateCharacters.length || mismatchedExamples.length) {
  throw new Error(
    `字库校验失败：重复 ${duplicateCharacters.map((item) => item.char).join(",")}；例词不匹配 ${mismatchedExamples
      .map((item) => item.char)
      .join(",")}`,
  );
}

export const wordCategories = ["全部", ...new Set(wordBank.map((entry) => entry.category))];
export const wordByCharacter = new Map(wordBank.map((entry) => [entry.char, entry]));

export function getWordCard(char: string) {
  const card = wordByCharacter.get(char);
  if (!card) throw new Error(`字库中没有找到“${char}”`);
  return card;
}
